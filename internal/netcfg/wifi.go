package netcfg

import (
	"fmt"
	"regexp"
	"strings"
)

// WifiDir is where the wireless configuration files live. They hold passphrases, so only root reads them.
const WifiDir = "/etc/gatehouse/wifi"

// Wifi is one wireless card. As a client it joins somebody else's network (use it as an internet
// connection by adding a connection on this port); as an access point it broadcasts a network of
// its own (use it as a LAN port, alone or as a member of a bridge).
type Wifi struct {
	Iface   string `json:"iface"`
	Mode    string `json:"mode"` // client or ap
	SSID    string `json:"ssid"`
	PSK     string `json:"psk,omitempty"` // plaintext only while applying; empty means an open client network
	Country string `json:"country"`       // two letters, sets the legal channels and power
	Band    string `json:"band"`          // ap: 2.4 or 5
	Channel int    `json:"channel"`       // ap: 0 picks a common one
	Hidden  bool   `json:"hidden"`        // client: the network does not announce its name; ap: do not announce
	WPA3    bool   `json:"wpa3"`          // ap: also allow WPA3 (devices that cannot use it still join with WPA2)
	Fast    bool   `json:"fast"`          // ap: use 802.11ac on 5 GHz; set only when the card supports it
	Enabled bool   `json:"enabled"`
}

var (
	reWifiIface = regexp.MustCompile(`^(wl|wlan)[A-Za-z0-9]{0,12}$`)
	reCountry   = regexp.MustCompile(`^[A-Z]{2}$`)
)

func noControl(s string) bool {
	for _, r := range s {
		if r < 0x20 || r == 0x7f {
			return false
		}
	}
	return true
}

// WifiUnit is the unit a card runs as; Services starts and stops these alongside the PPP links.
func WifiUnit(w Wifi) string { return "wifi-" + w.Mode + ":" + w.Iface }

func (c *Config) validateWifi() []string {
	var errs []string
	add := func(f string, a ...any) { errs = append(errs, fmt.Sprintf(f, a...)) }
	seen := map[string]bool{}
	wanOn := map[string]bool{}
	for _, w := range c.WANs {
		if w.Enabled {
			wanOn[w.Iface] = true
		}
	}
	lanOn := map[string]bool{}
	for _, i := range c.Interfaces {
		if !i.Enabled {
			continue
		}
		switch i.Kind {
		case "phys":
			lanOn[i.Name] = true
		case "vlan":
			lanOn[i.Parent] = true
		case "bridge":
			for _, m := range i.Members {
				lanOn[m] = true
			}
		}
	}
	for _, w := range c.Wifi {
		if !reWifiIface.MatchString(w.Iface) {
			add("%q is not a wireless card name", w.Iface)
			continue
		}
		if seen[w.Iface] {
			add("%s is listed twice", w.Iface)
		}
		seen[w.Iface] = true
		if w.Mode != "client" && w.Mode != "ap" {
			add("%s: choose whether the card joins a network or broadcasts one", w.Iface)
			continue
		}
		if !w.Enabled {
			continue
		}
		if n := len(w.SSID); n < 1 || n > 32 || !noControl(w.SSID) {
			add("%s: the network name must be 1 to 32 characters", w.Iface)
		}
		if !reCountry.MatchString(w.Country) {
			add("%s: choose the country the device is in (two letters, for example US)", w.Iface)
		}
		if !noControl(w.PSK) || len(w.PSK) > 63 {
			add("%s: the Wi-Fi password has characters that are not allowed", w.Iface)
		}
		if w.PSK != "" && len(w.PSK) < 8 {
			add("%s: a Wi-Fi password must be at least 8 characters", w.Iface)
		}
		switch w.Mode {
		case "ap":
			if w.PSK == "" {
				add("%s: a network you broadcast needs a password", w.Iface)
			}
			if w.Band != "2.4" && w.Band != "5" {
				add("%s: choose 2.4 GHz or 5 GHz", w.Iface)
			}
			if w.Channel < 0 || w.Channel > 196 {
				add("%s: that channel does not exist", w.Iface)
			}
			if !lanOn[w.Iface] {
				add("%s: give the access point a network (use it as a LAN port or add it to a bridge)", w.Iface)
			}
			if wanOn[w.Iface] {
				add("%s is broadcasting a network, so it cannot also be an internet connection", w.Iface)
			}
		case "client":
			if !wanOn[w.Iface] {
				add("%s: add an internet connection on this card so the network it joins gets used", w.Iface)
			}
			if lanOn[w.Iface] {
				add("%s joins another network, so it cannot also be a LAN port", w.Iface)
			}
		}
	}
	return errs
}

func (c *Config) generateWifi(out *Output) {
	for _, w := range c.Wifi {
		if !w.Enabled {
			continue
		}
		f := &file{}
		name := w.Iface
		switch w.Mode {
		case "client":
			f.l("# Generated by Gatehouse")
			f.l("ctrl_interface=/run/wpa_supplicant\nupdate_config=0\ncountry=%s\nap_scan=1", w.Country)
			f.l("network={\n\tssid=%s", hexSSID(w.SSID))
			if w.PSK == "" {
				f.l("\tkey_mgmt=NONE")
			} else if w.WPA3 {
				f.l("\tkey_mgmt=WPA-PSK SAE\n\tieee80211w=1\n\tpsk=\"%s\"\n\tsae_password=\"%s\"", w.PSK, w.PSK)
			} else {
				f.l("\tkey_mgmt=WPA-PSK\n\tpsk=\"%s\"", w.PSK)
			}
			if w.Hidden {
				f.l("\tscan_ssid=1")
			}
			f.l("}")
			name += ".supplicant.conf"
		case "ap":
			f.l("# Generated by Gatehouse")
			f.l("interface=%s\ndriver=nl80211\nctrl_interface=/run/hostapd", w.Iface)
			f.l("ssid=%s\nutf8_ssid=1\ncountry_code=%s\nieee80211d=1\nieee80211h=%d", w.SSID, w.Country, b2int(w.Band == "5"))
			ch := w.Channel
			if w.Band == "5" {
				if ch == 0 {
					ch = 36
				}
				f.l("hw_mode=a\nchannel=%d\nieee80211n=1\nwmm_enabled=1", ch)
				if w.Fast {
					f.l("ieee80211ac=1")
				}
			} else {
				if ch == 0 {
					ch = 6
				}
				f.l("hw_mode=g\nchannel=%d\nieee80211n=1\nwmm_enabled=1", ch)
			}
			if w.Hidden {
				f.l("ignore_broadcast_ssid=1")
			}
			f.l("auth_algs=1\nwpa=2\nrsn_pairwise=CCMP\nwpa_passphrase=%s", w.PSK)
			if w.WPA3 {
				f.l("wpa_key_mgmt=WPA-PSK SAE\nieee80211w=1\nsae_require_mfp=1\nsae_password=%s", w.PSK)
			} else {
				f.l("wpa_key_mgmt=WPA-PSK\nieee80211w=0")
			}
			name += ".hostapd.conf"
		}
		out.Wifi[name] = f.b.String()
		out.PPPUnits = append(out.PPPUnits, WifiUnit(w))
	}
}

func hexSSID(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		fmt.Fprintf(&b, "%02x", s[i])
	}
	return b.String()
}

func b2int(b bool) int {
	if b {
		return 1
	}
	return 0
}
