package fw

import (
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"gatehouse/internal/bridgemode"
)

// BridgeSetting is the settings key that holds the bridge mode setup as JSON.
const BridgeSetting = "net.bridge"

const bridgeTable = "gatehouse_br"

// BridgeFrom reads the saved bridge mode setup; nil when there is none.
func BridgeFrom(db Queryer) *bridgemode.Config {
	raw := strings.TrimSpace(setting(db, BridgeSetting, ""))
	if raw == "" {
		return nil
	}
	var c bridgemode.Config
	if json.Unmarshal([]byte(raw), &c) != nil {
		return nil
	}
	return &c
}

// BridgeOn says whether the bridge ruleset replaces the routing one.
func (m *Model) BridgeOn() bool { return m.Bridge != nil && m.Bridge.Enabled }

// compileBridge writes the ruleset for bridge mode: a bridge-family table that filters the frames
// crossing the bridge and decides which side may reach this machine, and the usual inet table with
// only the protected input rules. Nothing here routes or translates addresses.
func compileBridge(m *Model) (string, error) {
	b := m.Bridge
	if err := b.Validate(); err != nil {
		return "", err
	}
	if len(m.ConsolePorts) == 0 {
		return "", errors.New("the console port is not known")
	}
	c := &compiler{m: m}
	ports := portList(m.ConsolePorts)
	inside := ifSet(b.Inside)
	outside := q(b.Outside)

	// Inet table: this machine's own protection. Frames from the outside port were already
	// stopped by the bridge table below, so what reaches here from the bridge is from the inside
	// (or from a subnet named on purpose).
	c.line(0, "# Generated by Gatehouse (bridge mode). Do not edit; changes are overwritten on the next apply.")
	c.line(0, "add table inet %s", tableName)
	c.line(0, "delete table inet %s", tableName)
	c.line(0, "table inet %s {", tableName)
	for _, n := range []string{AcctUp, AcctDown} {
		c.line(1, "set %s { type ipv4_addr; flags dynamic, timeout; timeout 1h; size 8192; counter; }", n)
	}
	for _, n := range []string{AcctTo, AcctFrom} {
		c.line(1, "set %s { type ipv4_addr; flags dynamic, timeout; timeout 10m; size 65535; counter; }", n)
	}
	c.line(1, "chain input {")
	c.line(2, "type filter hook input priority filter; policy drop;")
	c.line(2, "ct state invalid drop")
	c.line(2, "ct state { established, related } accept")
	c.line(2, `iifname "lo" accept`)
	local := []string{bridgemode.Name}
	if b.OOB != "" {
		local = append(local, b.OOB)
	}
	lim := ""
	if len(m.MgmtAllow) > 0 {
		var a4 []string
		for _, cidr := range m.MgmtAllow {
			if !strings.Contains(cidr, ":") {
				a4 = append(a4, cidr)
			}
		}
		if len(a4) > 0 {
			lim = " ip saddr " + setLit(a4)
		}
	}
	c.line(2, "iifname %s%s tcp dport %s accept comment \"protected: management console\"", ifSet(local), lim, ports)
	if b.OOB != "" {
		c.line(2, "iifname %s tcp dport %s accept comment \"protected: management-only port\"", q(b.OOB), ports)
	}
	if m.SSHEnabled {
		c.line(2, "iifname %s%s tcp dport 22 accept comment \"protected: management ssh\"", ifSet(local), lim)
	}
	if m.SNMPEnabled {
		c.line(2, "iifname %s%s udp dport 161 accept comment \"protected: management snmp\"", ifSet(local), lim)
	}
	if r := m.RescueIface; r != "" && r != b.Outside {
		c.line(2, "iifname %s tcp dport %s accept comment \"protected: setup port\"", ifSet([]string{r}), ports)
	}
	c.line(2, "icmp type { destination-unreachable, time-exceeded, parameter-problem } accept")
	c.line(2, "icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept")
	c.line(2, "iifname %s icmp type echo-request limit rate 20/second accept", ifSet(local))
	c.line(2, "iifname %s meta l4proto { tcp, udp } th dport 53 accept comment \"dns\"", ifSet(local))
	c.line(2, "iifname %s udp sport 67 udp dport 68 accept comment \"management address from dhcp\"", q(bridgemode.Name))
	c.dropTail(2, "in")
	c.line(1, "}")
	c.line(1, "chain output {")
	c.line(2, "type filter hook output priority filter; policy accept;")
	c.line(1, "}")
	c.line(0, "}")

	// Bridge table: what crosses the bridge, and who may talk to this machine.
	c.line(0, "add table bridge %s", bridgeTable)
	c.line(0, "delete table bridge %s", bridgeTable)
	c.line(0, "table bridge %s {", bridgeTable)
	c.line(1, "chain input {")
	c.line(2, "type filter hook input priority filter; policy accept;")
	for _, s := range b.Subnets {
		c.line(2, "iifname %s ip saddr %s tcp dport %s accept comment \"protected: management from %s\"", outside, s, ports, s)
	}
	c.line(2, "iifname %s tcp dport %s counter drop comment \"console is not reachable from the outside\"", outside, ports)
	c.line(2, "iifname %s tcp dport 22 counter drop comment \"ssh is not reachable from the outside\"", outside)
	c.line(2, "iifname %s meta l4proto { tcp, udp } th dport 53 counter drop comment \"dns is for the inside only\"", outside)
	c.line(1, "}")
	c.line(1, "chain forward {")
	if b.Open {
		c.line(2, "type filter hook forward priority filter; policy accept;")
		c.line(2, "# Trial mode: everything passes; nothing is filtered.")
	} else {
		c.line(2, "type filter hook forward priority filter; policy drop;")
		c.line(2, "ct state invalid drop")
		c.line(2, "ct state { established, related } accept")
		c.line(2, "ether type arp accept")
		c.line(2, "iifname %s accept comment \"from the local network\"", inside)
		c.line(2, "iifname %s udp sport 67 udp dport 68 accept comment \"dhcp answers\"", outside)
		c.line(2, "iifname %s udp sport 547 udp dport 546 accept comment \"dhcpv6 answers\"", outside)
		c.line(2, "iifname %s icmp type { destination-unreachable, time-exceeded, parameter-problem } accept", outside)
		c.line(2, "iifname %s icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept", outside)
		for _, a := range b.Allow {
			c.line(2, "iifname %s ip daddr %s %s dport %d counter accept comment %s", outside, a.To, a.Proto, a.Port, q("allowed from outside: "+a.Name))
		}
		if m.LogDrops {
			c.line(2, "limit rate 20/second burst 50 packets log prefix %s", q(logPrefix("drop", "bridge: new connection from the outside")))
		}
		c.line(2, "counter drop comment \"default\"")
	}
	c.line(1, "}")
	c.line(0, "}")
	_ = fmt.Sprint
	return c.out.String(), nil
}
