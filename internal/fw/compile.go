package fw

import (
	"fmt"
	"net"
	"sort"
	"strconv"
	"strings"
)

const tableName = "gatehouse"

// Compile validates the model and returns an nftables script that replaces the whole
// gatehouse table in one atomic step. It never touches any other table.
func Compile(m *Model) (string, error) {
	if err := m.Validate(); err != nil {
		return "", err
	}
	c := &compiler{m: m}
	return c.build(), nil
}

type compiler struct {
	m   *Model
	out strings.Builder
}

func (c *compiler) line(indent int, f string, a ...any) {
	c.out.WriteString(strings.Repeat("\t", indent))
	fmt.Fprintf(&c.out, f, a...)
	c.out.WriteByte('\n')
}

func q(s string) string { return `"` + s + `"` }

// ifSet renders interface names as an nft set or a single quoted name.
func ifSet(names []string) string {
	n := append([]string(nil), names...)
	sort.Strings(n)
	n = uniq(n)
	for i := range n {
		n[i] = q(n[i])
	}
	if len(n) == 1 {
		return n[0]
	}
	return "{ " + strings.Join(n, ", ") + " }"
}

func uniq(s []string) []string {
	var out []string
	for i, v := range s {
		if i == 0 || v != s[i-1] {
			out = append(out, v)
		}
	}
	return out
}

func (c *compiler) ifaces(kinds ...string) []string {
	var out []string
	for _, z := range c.m.Zones {
		for _, k := range kinds {
			if z.Kind == k {
				out = append(out, z.Ifaces...)
			}
		}
	}
	return out
}

func (c *compiler) clientIfaces() []string {
	var out []string
	for _, z := range c.m.Zones {
		if z.Kind != KindWan {
			out = append(out, z.Ifaces...)
		}
	}
	return out
}

func portList(ports []int) string {
	s := make([]string, len(ports))
	for i, p := range ports {
		s[i] = strconv.Itoa(p)
	}
	if len(s) == 1 {
		return s[0]
	}
	return "{ " + strings.Join(s, ", ") + " }"
}

// zoneIfaces resolves a rule endpoint to interface names.
func (c *compiler) zoneIfaces(name string) []string {
	switch name {
	case "self":
		return nil
	case "wan":
		return c.m.WanIfaces()
	}
	if z, ok := c.m.ZoneByName(name); ok {
		return z.Ifaces
	}
	for _, z := range c.m.Zones { // names are matched case-insensitively
		if strings.EqualFold(z.Name, name) {
			return z.Ifaces
		}
	}
	return nil
}

func (c *compiler) build() string {
	m := c.m
	c.line(0, "# Generated by Gatehouse. Do not edit; changes are overwritten on the next apply.")
	c.line(0, "add table inet %s", tableName)
	c.line(0, "delete table inet %s", tableName)
	c.line(0, "table inet %s {", tableName)
	c.input()
	c.forward()
	c.line(1, "chain output {")
	c.line(2, "type filter hook output priority filter; policy accept;")
	c.line(1, "}")
	if wan := c.m.WanIfaces(); len(wan) > 0 {
		c.line(1, "chain clamp {")
		c.line(2, "type filter hook forward priority mangle; policy accept;")
		c.line(2, "oifname %s tcp flags & (syn|rst) == syn tcp option maxseg size set rt mtu", ifSet(wan))
		c.line(1, "}")
	}
	c.marks()
	c.nat()
	c.line(0, "}")
	_ = m
	return c.out.String()
}

func (c *compiler) dropTail(indent int, tag string) {
	if c.m.LogDrops {
		c.line(indent, `limit rate 5/minute log prefix "gh-drop-%s: "`, tag)
	}
	c.line(indent, "counter drop comment \"default\"")
}

func (c *compiler) input() {
	m := c.m
	c.line(1, "chain input {")
	c.line(2, "type filter hook input priority filter; policy drop;")
	c.line(2, "ct state invalid drop")
	c.line(2, "ct state { established, related } accept")
	c.line(2, `iifname "lo" accept`)

	// The protected management rule: always first among the accepts, and not part of the editable model.
	var mgmt, ssh []string
	for _, z := range m.Zones {
		if z.Management {
			mgmt = append(mgmt, z.Ifaces...)
		}
		if z.SSH && z.Management {
			ssh = append(ssh, z.Ifaces...)
		}
	}
	c.line(2, "iifname %s tcp dport %s accept comment \"protected: management console\"", ifSet(mgmt), portList(m.ConsolePorts))
	if len(ssh) > 0 {
		c.line(2, "iifname %s tcp dport 22 accept comment \"protected: management ssh\"", ifSet(ssh))
	}

	// Basic protocol health.
	c.line(2, "icmp type { destination-unreachable, time-exceeded, parameter-problem } accept")
	c.line(2, "icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept")
	clients := c.clientIfaces()
	if len(clients) > 0 {
		c.line(2, "iifname %s icmp type echo-request limit rate 20/second accept", ifSet(clients))
		c.line(2, "iifname %s icmpv6 type echo-request limit rate 20/second accept", ifSet(clients))
		c.line(2, "iifname %s udp dport 67 accept comment \"dhcp server\"", ifSet(clients))
		c.line(2, "iifname %s meta l4proto { tcp, udp } th dport 53 accept comment \"dns\"", ifSet(clients))
	}
	if wan := m.WanIfaces(); len(wan) > 0 {
		c.line(2, "iifname %s udp sport 67 udp dport 68 accept comment \"wan dhcp client\"", ifSet(wan))
		c.line(2, "iifname %s udp sport 547 udp dport 546 accept comment \"wan dhcpv6 client\"", ifSet(wan))
	}

	// Explicit exceptions that target the router itself.
	for _, r := range m.Rules {
		if r.Enabled && r.To == "self" {
			c.explicit(2, r, false)
		}
	}
	c.dropTail(2, "in")
	c.line(1, "}")
}

func (c *compiler) forward() {
	m := c.m
	c.line(1, "chain forward {")
	c.line(2, "type filter hook forward priority filter; policy drop;")
	c.line(2, "ct state invalid drop")
	c.line(2, "ct state { established, related } accept")
	wan := m.WanIfaces()
	if m.BlockDoT && len(wan) > 0 {
		c.line(2, "iifname %s oifname %s tcp dport 853 counter drop comment \"block dns-over-tls bypass\"", ifSet(c.clientIfaces()), ifSet(wan))
	}
	if len(m.Forwards) > 0 {
		c.line(2, "ct status dnat accept comment \"port forwards\"")
	}
	for _, r := range m.Rules {
		if r.Enabled && r.To != "self" {
			c.explicit(2, r, true)
		}
	}
	all := c.clientIfaces()
	for _, z := range m.Zones {
		if z.Kind == KindWan || len(z.Ifaces) == 0 {
			continue
		}
		if z.Internet && z.Gateway && len(wan) > 0 {
			c.line(2, "iifname %s oifname %s counter accept comment %s", ifSet(z.Ifaces), ifSet(wan), q("internet:"+z.Name))
		}
		if z.Kind == KindTrusted && z.Gateway {
			var others []string
			for _, i := range all {
				if !contains(z.Ifaces, i) {
					others = append(others, i)
				}
			}
			if len(others) > 0 {
				c.line(2, "iifname %s oifname %s counter accept comment %s", ifSet(z.Ifaces), ifSet(others), q("trusted:"+z.Name))
			}
		}
		if z.IntraAllow {
			c.line(2, "iifname %s oifname %s counter accept comment %s", ifSet(z.Ifaces), ifSet(z.Ifaces), q("within:"+z.Name))
		}
	}
	c.dropTail(2, "fwd")
	c.line(1, "}")
}

func contains(s []string, v string) bool {
	for _, x := range s {
		if x == v {
			return true
		}
	}
	return false
}

// explicit renders one exception rule, expanding services and address families.
func (c *compiler) explicit(indent int, r Rule, forward bool) {
	m := c.m
	from := c.zoneIfaces(r.From)
	var to []string
	if forward {
		to = c.zoneIfaces(r.To)
		if len(from) == 0 || len(to) == 0 {
			return
		}
	} else if len(from) == 0 {
		return
	}
	src, srcAny, _ := parseAddrs(r.Src, m.Groups, 0)
	dst, dstAny, _ := parseAddrs(r.Dst, m.Groups, 0)
	specs, _ := ParseService(r.Service)

	type fam struct{ s, d string }
	var fams []fam
	add := func(s, d string) { fams = append(fams, fam{s, d}) }
	sf := func(set addrSet, isAny bool, kw string) (a4, a6 string) {
		if isAny {
			return "", ""
		}
		if len(set.v4) > 0 {
			a4 = "ip " + kw + " " + setLit(set.v4)
		}
		if len(set.v6) > 0 {
			a6 = "ip6 " + kw + " " + setLit(set.v6)
		}
		return
	}
	s4, s6 := sf(src, srcAny, "saddr")
	d4, d6 := sf(dst, dstAny, "daddr")
	switch {
	case srcAny && dstAny:
		add("", "")
	case srcAny:
		if d4 != "" {
			add("", d4)
		}
		if d6 != "" {
			add("", d6)
		}
	case dstAny:
		if s4 != "" {
			add(s4, "")
		}
		if s6 != "" {
			add(s6, "")
		}
	default:
		if s4 != "" && d4 != "" {
			add(s4, d4)
		}
		if s6 != "" && d6 != "" {
			add(s6, d6)
		}
	}
	if len(specs) == 0 {
		specs = []PortSpec{{}}
	}
	for _, f := range fams {
		for _, sp := range specs {
			var b strings.Builder
			b.WriteString("iifname " + ifSet(from))
			if forward {
				b.WriteString(" oifname " + ifSet(to))
			}
			if f.s != "" {
				b.WriteString(" " + f.s)
			}
			if f.d != "" {
				b.WriteString(" " + f.d)
			}
			if sp.Proto != "" {
				b.WriteString(" " + sp.matchExpr())
			}
			if r.Limit > 0 {
				fmt.Fprintf(&b, " limit rate %d/second", r.Limit)
			}
			if r.Log {
				fmt.Fprintf(&b, " log prefix %s", q("gh-"+r.Action+": "))
			}
			fmt.Fprintf(&b, " counter %s comment %s", r.Action, q("rule:"+r.From+":"+r.To+":"+r.Name))
			c.line(indent, "%s", b.String())
		}
	}
}

func setLit(v []string) string {
	if len(v) == 1 {
		return v[0]
	}
	return "{ " + strings.Join(v, ", ") + " }"
}

func (c *compiler) nat() {
	m := c.m
	wan := m.WanIfaces()
	redirect := m.DNSRedirect && len(c.clientIfaces()) > 0
	if !redirect && len(m.Forwards) == 0 && len(wan) == 0 {
		return
	}
	c.line(1, "chain prerouting {")
	c.line(2, "type nat hook prerouting priority dstnat; policy accept;")
	if redirect {
		c.line(2, "iifname %s meta l4proto { tcp, udp } th dport 53 redirect to :53 comment \"dns enforcement\"", ifSet(c.clientIfaces()))
	}
	for _, f := range m.Forwards {
		if !f.Enabled {
			continue
		}
		in := wan
		if f.WAN != "" {
			in = []string{f.WAN}
		}
		if len(in) == 0 {
			continue
		}
		port := f.IntPort
		if port == "" {
			port = f.ExtPort
		}
		ip := net.ParseIP(f.IntAddr)
		var target string
		if ip.To4() != nil {
			target = fmt.Sprintf("dnat ip to %s:%s", ip.To4(), strings.ReplaceAll(port, "-", "-"))
		} else {
			target = fmt.Sprintf("dnat ip6 to [%s]:%s", ip, port)
		}
		c.line(2, "iifname %s %s dport %s counter %s comment %s", ifSet(in), f.Proto, f.ExtPort, target, q("forward:"+f.Name))
	}
	c.line(1, "}")
	if len(wan) > 0 {
		c.line(1, "chain postrouting {")
		c.line(2, "type nat hook postrouting priority srcnat; policy accept;")
		c.line(2, "meta nfproto ipv4 oifname %s masquerade", ifSet(wan))
		c.line(1, "}")
	}
}

// MarkBase is the firewall mark of the first internet connection; link i uses MarkBase+i.
// The routing monitor installs the matching "ip rule" so marked packets use that link's table.
const MarkBase = 0x100

// marks makes replies leave through the connection a request arrived on. It is only needed
// with more than one internet connection.
func (c *compiler) marks() {
	wan := c.m.WanIfaces()
	if len(wan) < 2 {
		return
	}
	c.line(1, "chain wanmark {")
	c.line(2, "type filter hook prerouting priority mangle; policy accept;")
	for i, d := range wan {
		c.line(2, "iifname %s ct state new ct mark set 0x%x", q(d), MarkBase+i)
	}
	// Only packets that did not arrive from the internet pick up the mark. Marking an incoming
	// packet would route it by the mark's table before forwarding and send it straight back out.
	c.line(2, "iifname != %s ct mark != 0 meta mark set ct mark", ifSet(wan))
	c.line(1, "}")
	c.line(1, "chain wanmark_out {")
	c.line(2, "type route hook output priority mangle; policy accept;")
	c.line(2, "ct mark != 0 meta mark set ct mark")
	c.line(1, "}")
}
