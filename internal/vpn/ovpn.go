// ImportProfile reads a provider's .ovpn file. It keeps the certificates and the security
// settings, refuses anything that could run commands, and drops what the router controls.
func ImportProfile(text string) (*ImportedProfile, error) {
	if len(text) > 256*1024 {
		return nil, errors.New("that file is too large to be a VPN profile")
	}
	var out strings.Builder
	ip := &ImportedProfile{}
	lines := strings.Split(strings.ReplaceAll(text, "\r\n", "\n"), "\n")
	hasCA, hasRemote := false, false
	for i := 0; i < len(lines); i++ {
		line := strings.TrimSpace(lines[i])
		if line == "" || line[0] == '#' || line[0] == ';' {
			continue
		}
		if strings.HasPrefix(line, "<") && strings.HasSuffix(line, ">") && !strings.HasPrefix(line, "</") {
			tag := strings.Trim(line, "<>")
			end := "</" + tag + ">"
			var body []string
			closed := false
			for i++; i < len(lines); i++ {
				if strings.TrimSpace(lines[i]) == end {
					closed = true
					break
				}
				body = append(body, lines[i])
			}
			if !closed {
				return nil, fmt.Errorf("the <%s> section is not closed", tag)
			}
			if !inlineTags[tag] {
				return nil, fmt.Errorf("this profile uses <%s>, which is not supported", tag)
			}
			if tag == "ca" {
				hasCA = true
			}
			fmt.Fprintf(&out, "<%s>\n%s\n</%s>\n", tag, strings.Join(body, "\n"), tag)
			continue
		}
		f := strings.Fields(line)
		d := strings.ToLower(f[0])
		switch {
		case d == "auth-user-pass":
			if len(f) > 1 {
				return nil, errors.New("this profile reads its password from a file; paste a profile without that and enter the username and password in Gatehouse")
			}
			ip.NeedsAuth = true
		case d == "remote":
			if len(f) < 2 {
				return nil, errors.New("a remote line has no server")
			}
			hasRemote = true
			if ip.Remote == "" {
				ip.Remote = f[1]
			}
			fmt.Fprintln(&out, strings.Join(f, " "))
		case ignored[d]:
			// dropped
		case allowed[d]:
			for _, a := range f[1:] {
				if strings.ContainsAny(a, "`$;|&<>") {
					return nil, fmt.Errorf("the %q setting contains characters that are not allowed", d)
				}
			}
			fmt.Fprintln(&out, strings.Join(f, " "))
		default:
			return nil, fmt.Errorf("this profile uses %q, which Gatehouse does not run for safety. Ask your provider for a standard profile", d)
		}
	}
	if !hasRemote {
		return nil, errors.New("that profile does not name a server (no remote line)")
	}
	if !hasCA {
		return nil, errors.New("that profile has no embedded certificate (<ca>). Use the single-file .ovpn from your provider")
	}
	ip.Config = out.String()
	return ip, nil
}

// OVPNClientConfig wraps an imported profile with the settings the router controls.
func OVPNClientConfig(imp *ImportedProfile, dev, authFile string) string {
	var b strings.Builder
	b.WriteString("# Generated by Gatehouse. The provider's profile with routes and DNS left to the router.\n")
	fmt.Fprintf(&b, "dev %s\ndev-type tun\nroute-nopull\nscript-security 1\n", dev)
	b.WriteString("pull-filter ignore \"redirect-gateway\"\npull-filter ignore \"route\"\npull-filter ignore \"dhcp-option\"\npull-filter ignore \"block-outside-dns\"\n")
	if authFile != "" {
		fmt.Fprintf(&b, "auth-user-pass %s\n", authFile)
	}
	b.WriteString(imp.Config)
	return b.String()
}
