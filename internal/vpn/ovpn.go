package vpn

import (
	"errors"
	"fmt"
	"net/netip"
	"strings"
)

// Ciphers are limited to modern authenticated encryption.
const dataCiphers = "AES-256-GCM:CHACHA20-POLY1305:AES-128-GCM"

// OVPNServer is everything the OpenVPN server configuration needs.
type OVPNServer struct {
	Dev      string // tun0
	Proto    string // udp or tcp
	Port     int
	Subnet   string   // 10.9.0.0/24
	DNS      string   // pushed resolver, usually the router's tunnel address
	RouteAll bool     // push a default route
	Routes   []string // networks to push so devices can reach them
	Dir      string   // where the key files live
}

func mask(p netip.Prefix) string {
	bits := p.Bits()
	var m [4]byte
	for i := 0; i < 4; i++ {
		n := bits - 8*i
		switch {
		case n >= 8:
			m[i] = 255
		case n > 0:
			m[i] = byte(0xff << (8 - n))
		}
	}
	return fmt.Sprintf("%d.%d.%d.%d", m[0], m[1], m[2], m[3])
}

// ServerAddr is the router's own address inside the OpenVPN network.
func ServerAddr(subnet string) (string, error) {
	a, err := ServerAddress(subnet)
	if err != nil {
		return "", err
	}
	p, _ := netip.ParsePrefix(a)
	return p.Addr().String(), nil
}

// Config renders the server's configuration file.
func (s OVPNServer) Config() (string, error) {
	p, err := netip.ParsePrefix(s.Subnet)
	if err != nil || !p.Addr().Is4() {
		return "", errors.New("the VPN network must look like 10.9.0.0/24")
	}
	p = p.Masked()
	if s.Proto != "udp" && s.Proto != "tcp" {
		return "", errors.New("protocol must be udp or tcp")
	}
	if s.Port < 1 || s.Port > 65535 {
		return "", errors.New("port must be between 1 and 65535")
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# Generated by Gatehouse. Changes are overwritten.")
	w("dev %s\ndev-type tun", s.Dev)
	if s.Proto == "udp" {
		w("proto udp4")
	} else {
		w("proto tcp4-server")
	}
	w("port %d", s.Port)
	w("server %s %s\ntopology subnet", p.Addr(), mask(p))
	w("ca %s/ca.crt\ncert %s/server.crt\nkey %s/server.key\ndh none", s.Dir, s.Dir, s.Dir)
	w("tls-crypt %s/tls-crypt.key", s.Dir)
	w("crl-verify %s/crl.pem", s.Dir)
	w("tls-version-min 1.2\ndata-ciphers %s\nauth SHA256", dataCiphers)
	w("keepalive 10 60\npersist-key\npersist-tun\nuser nobody\ngroup nogroup\nverb 1")
	if s.Proto == "udp" {
		w("explicit-exit-notify 1")
	}
	if s.DNS != "" {
		w(`push "dhcp-option DNS %s"`, s.DNS)
	}
	if s.RouteAll {
		w(`push "redirect-gateway def1"`)
	}
	for _, r := range s.Routes {
		rp, err := netip.ParsePrefix(r)
		if err != nil || !rp.Addr().Is4() {
			return "", fmt.Errorf("%q is not an address range", r)
		}
		rp = rp.Masked()
		w(`push "route %s %s"`, rp.Addr(), mask(rp))
	}
	return b.String(), nil
}

// Profile is the single file a device imports.
type Profile struct {
	Host       string
	Port       int
	Proto      string
	CA         string
	Cert       string
	Key        string
	TLSCrypt   string
	NoRedirect bool
}

func (p Profile) Text() string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("client\ndev tun")
	if p.Proto == "tcp" {
		w("proto tcp-client")
	} else {
		w("proto udp")
	}
	w("remote %s %d\nresolv-retry infinite\nnobind\npersist-key\npersist-tun", p.Host, p.Port)
	w("remote-cert-tls server\ndata-ciphers %s\nauth SHA256\nverb 1", dataCiphers)
	blk := func(tag, body string) { w("<%s>\n%s</%s>", tag, strings.TrimRight(body, "\n")+"\n", tag) }
	blk("ca", p.CA)
	blk("cert", p.Cert)
	blk("key", p.Key)
	blk("tls-crypt", p.TLSCrypt)
	return b.String()
}

// Imported is a provider's profile after it has been reduced to what is safe to run.
type ImportedProfile struct {
	Config    string // sanitised text, without dev, routes or credentials
	NeedsAuth bool   // asks for a username and password
	Remote    string // first remote, for display
}

